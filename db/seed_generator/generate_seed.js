const PROBLEM_COUNT = 250;
const PERIOD_START = Date.UTC(2026, 1, 20); // 2026-02-20
const PERIOD_END = Date.UTC(2026, 7, 20);   // 2026-08-20 (today)
const priorities = ['LOW', 'LOW', 'MEDIUM', 'MEDIUM', 'MEDIUM', 'HIGH', 'HIGH', 'CRITICAL'];
const leafHeavyTypeIds = [18, 19, 20, 21, 22, 7, 8, 10, 13, 15, 16, 17];
