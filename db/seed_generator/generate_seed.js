for (let pid = 1; pid <= PROBLEM_COUNT; pid++) {
  const loggedAtMs = PERIOD_START + Math.floor(rnd() * (PERIOD_END - PERIOD_START - 86400000));
  const logged_at = new Date(loggedAtMs);

  const caller_employee_id = randInt(1, EMPLOYEE_COUNT);
  const equipment_id = randInt(1, EQUIPMENT_COUNT);
  const problem_type_id = chance(0.65) ? pick(leafHeavyTypeIds) : pick(allAssignableTypeIds.filter((id) => id > 5));
  const logged_by_staff_id = randInt(1, 6); // an operator
  const priority = pick(priorities);

  // outcome distribution: 70% CLOSED, 15% RESOLVED, 15% still open (OPEN/ASSIGNED/IN_PROGRESS)
  const roll = rnd();
  let status;
  if (roll < 0.70) status = 'CLOSED';
  else if (roll < 0.85) status = 'RESOLVED';
  else status = pick(['OPEN', 'OPEN', 'ASSIGNED', 'IN_PROGRESS']);

  let assigned_staff_id = null;
  if (status !== 'OPEN') {
    assigned_staff_id = assignLeastLoaded(problem_type_id, loggedAtMs);
  }

  let resolved_at = null, resolution_notes = null, minutes_to_resolve = null;
  if (status === 'RESOLVED' || status === 'CLOSED') {
    const priorityCapMinutes = { CRITICAL: 240, HIGH: 720, MEDIUM: 2880, LOW: 5760 }[priority];
    const durationMin = randInt(15, priorityCapMinutes);
    const resolvedMs = Math.min(loggedAtMs + durationMin * 60000, PERIOD_END - 3600000);
    resolved_at = new Date(Math.max(resolvedMs, loggedAtMs + 60000));
    minutes_to_resolve = Math.round((resolved_at.getTime() - loggedAtMs) / 60000);
    resolution_notes = `Resolved by reproducing the issue and applying the standard fix for ${typeById[problem_type_id].name.toLowerCase()}.`;
    // problem stays open in the tracker only up to its resolution — decrement load
    if (assigned_staff_id) openLoad[assigned_staff_id] = Math.max(0, (openLoad[assigned_staff_id] || 0));
  } else if (assigned_staff_id) {
    openLoad[assigned_staff_id] = (openLoad[assigned_staff_id] || 0) + 1;
  }

  problems.push({
    problem_id: pid, caller_employee_id, equipment_id, problem_type_id,
    status, priority, assigned_staff_id, logged_by_staff_id, logged_at,
    resolved_at, resolution_notes, minutes_to_resolve,
  });

  callLogs.push({
    call_log_id: callLogIdSeq++, problem_id: pid, staff_id: logged_by_staff_id,
    call_type: 'INITIAL',
    notes: `Caller reported: ${typeById[problem_type_id].name.toLowerCase()} on equipment logged at intake.`,
    logged_at,
  });

  // budgeted to land total call_log rows near the ~400 target in §3.7
  const generalFollowUp = chance(0.2);
  if (generalFollowUp) {
    const followUpStaff = assigned_staff_id || logged_by_staff_id;
    const offsetMs = Math.floor((rnd() * (resolved_at ? resolved_at.getTime() - loggedAtMs : 86400000 * 2)));
    callLogs.push({
      call_log_id: callLogIdSeq++, problem_id: pid, staff_id: followUpStaff,
      call_type: 'FOLLOW_UP',
      notes: 'Follow-up: gathered further diagnostic detail from the caller.',
      logged_at: new Date(loggedAtMs + offsetMs + 60000),
    });
  }
  if (resolved_at && assigned_staff_id && chance(0.65)) {
    callLogs.push({
      call_log_id: callLogIdSeq++, problem_id: pid, staff_id: assigned_staff_id,
      call_type: 'FOLLOW_UP',
      notes: `Resolved: ${resolution_notes}`,
      logged_at: resolved_at,
    });
  }
}

