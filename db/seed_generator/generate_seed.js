// ---------------------------------------------------------------------
// Mirror of fn_find_specialist + sp_assign_least_loaded, in JS, so the
// generator can pick internally-consistent assignments (and so Phase 3
// checkpoint output has a known-correct answer to check the real SQL
// routines against).
// ---------------------------------------------------------------------
const typeById = Object.fromEntries(problemTypes.map((t) => [t.id, t]));
const expertiseByType = {};
for (const e of expertise) {
  (expertiseByType[e.problem_type_id] = expertiseByType[e.problem_type_id] || []).push(e.staff_id);
}
function findSpecialistTypeId(problemTypeId) {
  let cur = typeById[problemTypeId];
  while (cur) {
    if (expertiseByType[cur.id] && expertiseByType[cur.id].length > 0) return cur.id;
    cur = cur.parent ? typeById[cur.parent] : null;
  }
  return null;
}
// running open-load tracker used only to make seed assignment plausible
const openLoad = {}; // staff_id -> count
const lastAssignedAt = {}; // staff_id -> ms timestamp
function assignLeastLoaded(problemTypeId, atTime) {
  const resolvedTypeId = findSpecialistTypeId(problemTypeId);
  if (resolvedTypeId === null) return null;
  const candidates = expertiseByType[resolvedTypeId];
  let best = null;
  for (const staffId of candidates) {
    const load = openLoad[staffId] || 0;
    const last = lastAssignedAt[staffId] || 0;
    if (best === null || load < best.load || (load === best.load && last < best.last)) {
      best = { staffId, load, last };
    }
  }
  lastAssignedAt[best.staffId] = atTime;
  return best.staffId;
}

